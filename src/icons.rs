/// Lucide's own synonyms for each icon, as JSON. Search by meaning rather
/// than by spelling: "cut" has to find the scissors.
pub const TAGS_JSON: &str = include_str!("../assets/icon-tags.json");

/// Looks up a bundled icon by name.
pub fn get(name: &str) -> Option<&'static str> {
    // The table is sorted, and there are nearly two thousand entries.
    ICONS
        .binary_search_by_key(&name, |(icon, _)| icon)
        .ok()
        .map(|index| ICONS[index].1)
}

/// Every bundled icon name.
pub fn names() -> Vec<&'static str> {
    ICONS.iter().map(|(name, _)| *name).collect()
}
